#!/usr/bin/env python3
"""Generate a Quantumult X ruleset from OpenAI's ChatGPT Voice IP list."""

from __future__ import annotations

import argparse
import ipaddress
import json
import urllib.request
from pathlib import Path
from typing import Any, Iterator

SOURCE_URL = "https://openai.com/chatgpt-voice.json"
USER_AGENT = "QuanX-ChatGPTVoice-Rules-Updater/1.0"
REQUEST_TIMEOUT_SECONDS = 30


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate Quantumult X rules from OpenAI ChatGPT Voice IP ranges."
    )
    parser.add_argument(
        "--source-url",
        default=SOURCE_URL,
        help=f"JSON source URL (default: {SOURCE_URL})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("ChatGPTVoice.list"),
        help="Output ruleset path (default: next to this script)",
    )
    return parser.parse_args()


def load_json(url: str) -> Any:
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/json",
            "User-Agent": USER_AGENT,
        },
    )
    with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT_SECONDS) as response:
        # The official endpoint currently uses application/octet-stream while
        # returning UTF-8 JSON, so parse the body instead of checking the header.
        body = response.read().decode("utf-8-sig")
    return json.loads(body)


def iter_strings(value: Any) -> Iterator[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for child in value.values():
            yield from iter_strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from iter_strings(child)


def collect_networks(value: Any) -> list[ipaddress._BaseNetwork]:
    networks: dict[tuple[int, int, int], ipaddress._BaseNetwork] = {}

    for candidate in iter_strings(value):
        try:
            network = ipaddress.ip_network(candidate, strict=False)
        except ValueError:
            continue

        key = (
            network.version,
            int(network.network_address),
            network.prefixlen,
        )
        networks[key] = network

    return sorted(
        networks.values(),
        key=lambda network: (
            network.version,
            int(network.network_address),
            network.prefixlen,
        ),
    )


def render_rules(networks: list[ipaddress._BaseNetwork], source_url: str) -> str:
    lines = [
        "# ChatGPT Voice IP ranges for Quantumult X",
        f"# Source: {source_url}",
        "# Auto-generated by update_chatgpt_voice.py",
        "# Configure force-policy in [filter_remote] to select your proxy policy.",
        "",
    ]

    for network in networks:
        rule_type = "ip-cidr" if network.version == 4 else "ip6-cidr"
        lines.append(f"{rule_type}, {network}, no-resolve")

    return "\n".join(lines) + "\n"


def write_atomically(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = path.with_name(f".{path.name}.tmp")
    temporary_path.write_text(content, encoding="utf-8", newline="\n")
    temporary_path.replace(path)


def main() -> None:
    args = parse_args()
    data = load_json(args.source_url)
    networks = collect_networks(data)

    if not networks:
        raise RuntimeError("No valid IPv4/IPv6 CIDR entries found in the source JSON.")

    content = render_rules(networks, args.source_url)
    write_atomically(args.output, content)
    print(f"Generated {len(networks)} Quantumult X rules in {args.output}.")


if __name__ == "__main__":
    main()
